"""Write config_test_mix.yaml (no separation: CREPE on the full mix) and
config_test_oracle.yaml (true isolated voice installed as the 'oracle' stem,
ranked above Demucs) from config.yaml, for the synthetic test runs."""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
for name in ("mix", "oracle"):
    c = yaml.safe_load((ROOT / "config.yaml").read_text())
    c["paths"]["output_dir"] = f"output_test_{name}"
    if name == "mix":
        c["separation"]["enabled"] = False
    else:
        c["separation"]["reuse_models"] = ["oracle"] + c["separation"]["reuse_models"]
    (ROOT / f"config_test_{name}.yaml").write_text(
        f"# TEST config ({name}), generated by scripts/make_test_configs.py\n"
        + yaml.safe_dump(c, sort_keys=False))
